// Fallback helper ensures any of the 22 languages gracefully resolve without missing strings
export const getTranslation = (langCode, key) => {
  const lang = translations[langCode] || translations.en;
  if (lang[key]) return lang[key];
  if (translations.hi && translations.hi[key]) return translations.hi[key];
  if (translations.mr && translations.mr[key]) return translations.mr[key];
  return translations.en[key] || key;
};
